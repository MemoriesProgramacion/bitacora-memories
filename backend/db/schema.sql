CREATE OR REPLACE VIEW vw_unidades_productivas AS
SELECT  up.id_up, up.id_unico, t.nodo, t.region, t.triada, up.tipo,
        up.nombre AS nombre_up, up.nit, up.sector, up.modalidad,
        up.departamento, up.municipio, up.habilitada, up.retirada_dps,
        r.documento AS documento_representante, r.nombre_completo AS representante,
        r.telefono1, r.correo1, up.enlace_carpeta, up.fecha_actualizacion
FROM unidades_productivas up
LEFT JOIN triadas t        ON t.id_triada = up.id_triada
LEFT JOIN representantes r ON r.id_representante = up.id_representante;

CREATE OR REPLACE VIEW vw_avance_expedientes AS
SELECT  up.id_unico, up.nombre AS nombre_up, t.triada,
        COUNT(ee.id_expediente_etapa)                              AS etapas_registradas,
        COUNT(*) FILTER (WHERE ee.completa)                        AS etapas_completas,
        CAST(100.0 * COUNT(*) FILTER (WHERE ee.completa)
             / NULLIF(COUNT(ee.id_expediente_etapa), 0) AS NUMERIC(5,1)) AS pct_avance
FROM unidades_productivas up
JOIN expedientes_up e             ON e.id_up = up.id_up
LEFT JOIN expediente_etapas ee    ON ee.id_expediente = e.id_expediente
LEFT JOIN triadas t               ON t.id_triada = up.id_triada
GROUP BY up.id_unico, up.nombre, t.triada;

