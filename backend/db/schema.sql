CREATE INDEX IF NOT EXISTS ix_novedad_dest_nodo ON novedad_destinatarios (nodo);

-- Lista de compras de cada unidad productiva.
CREATE TABLE IF NOT EXISTS listas_compra (
    id                   VARCHAR(80) PRIMARY KEY,
    id_up                INTEGER NULL REFERENCES unidades_productivas (id_up),
    id_unico             VARCHAR(50)  NOT NULL,
    nodo                 VARCHAR(100) NULL,
    unidad_nombre        VARCHAR(300) NULL,
    kit                  VARCHAR(50)  NULL,
    fecha_tentativa      DATE NULL,
    confirmado_por       VARCHAR(200) NULL,
    fecha_confirmacion   TIMESTAMPTZ NULL,
    actor_cedula         VARCHAR(30)  NULL,
    actor_nombre         VARCHAR(200) NULL,
    actor_puesto         VARCHAR(150) NULL,
    creado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_listas_compra_up UNIQUE (id_unico)
);
CREATE INDEX IF NOT EXISTS ix_listas_compra_nodo ON listas_compra (nodo);

-- Ítems de cada lista de compras.
CREATE TABLE IF NOT EXISTS lista_compra_items (
    id_lista   VARCHAR(80)  NOT NULL REFERENCES listas_compra (id) ON DELETE CASCADE,
    item_id    VARCHAR(30)  NOT NULL,
    nombre     VARCHAR(300) NOT NULL,
    comprado   BOOLEAN NOT NULL DEFAULT FALSE,
    orden      INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (id_lista, item_id)
);

-- Entrega programada a cada unidad productiva, con su estado y hora.
CREATE TABLE IF NOT EXISTS entregas (
    id                   VARCHAR(80) PRIMARY KEY,
    id_up                INTEGER NULL REFERENCES unidades_productivas (id_up),
    id_unico             VARCHAR(50)  NOT NULL,
    nodo                 VARCHAR(100) NULL,
    unidad_nombre        VARCHAR(300) NULL,
    fecha_tentativa      DATE NULL,
    telefono             VARCHAR(60)  NULL,
    direccion            VARCHAR(300) NULL,
    hora_confirmada      DATE NULL,
    estado_hora          VARCHAR(20)  NULL,

    sol_motivo           TEXT NULL,
    sol_fecha_anterior   DATE NULL,
    sol_fecha_sugerida   DATE NULL,
    sol_gestor           VARCHAR(200) NULL,
    sol_nodo             VARCHAR(100) NULL,
    sol_solicitado_en    TIMESTAMPTZ NULL,
    actor_cedula         VARCHAR(30)  NULL,
    actor_nombre         VARCHAR(200) NULL,
    actor_puesto         VARCHAR(150) NULL,
    creado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_entregas_up UNIQUE (id_unico),
    CONSTRAINT ck_entregas_estado CHECK
      (estado_hora IS NULL OR estado_hora IN ('tentativa', 'confirmada', 'solicitud', 'reagendada'))
);
CREATE INDEX IF NOT EXISTS ix_entregas_nodo   ON entregas (nodo);
CREATE INDEX IF NOT EXISTS ix_entregas_estado ON entregas (estado_hora);

-- Solicitudes de reagendamiento de las entregas.
CREATE TABLE IF NOT EXISTS entrega_reagendamientos (
    id_reagendamiento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entrega         VARCHAR(80) NOT NULL REFERENCES entregas (id) ON DELETE CASCADE,
    orden              INTEGER NOT NULL,
    fecha_anterior     DATE NULL,
    fecha_nueva        DATE NULL,
    motivo             TEXT NULL,
    gestor             VARCHAR(200) NULL,
    solicitado_en      TIMESTAMPTZ NULL,
    nota_coordinacion  TEXT NULL,
    coordinador        VARCHAR(200) NULL,
    fecha_registro     TIMESTAMPTZ NULL,
    CONSTRAINT uq_entrega_reag UNIQUE (id_entrega, orden)
);
