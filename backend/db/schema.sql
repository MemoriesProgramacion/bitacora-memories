-- Esquema base de la base de datos PostgreSQL de la Bitácora Memories. Define las tablas de
-- territorio, usuarios, unidades productivas, expedientes por etapas, validador de entregas, catálogo,
-- carritos, archivos, visitas, eventos, avisos, compras y entregas. Se puede ejecutar varias veces porque cada
-- tabla se crea solo si no existe.
-- Nodos del programa: cada tríada agrupa región y nodo.
CREATE TABLE IF NOT EXISTS triadas (
    id_triada   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nodo        VARCHAR(100) NOT NULL,
    region      VARCHAR(100) NOT NULL,
    triada      VARCHAR(100) NOT NULL,
    CONSTRAINT uq_triadas UNIQUE (nodo, region, triada)
);
CREATE INDEX IF NOT EXISTS ix_triadas_nodo ON triadas (nodo);

-- Cuentas de campo, una por nodo, que atienden las unidades productivas.
CREATE TABLE IF NOT EXISTS gestores (
    id_gestor            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen            VARCHAR(100) NOT NULL,
    id_triada            INTEGER NULL REFERENCES triadas (id_triada),
    tipo                 VARCHAR(50)  NULL,
    cedula               VARCHAR(20)  NOT NULL,
    nombre               VARCHAR(200) NOT NULL,
    correo               VARCHAR(150) NULL,
    telefono             VARCHAR(30)  NULL,

    clave_hash           VARCHAR(256) NULL,
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion  TIMESTAMPTZ NULL,
    CONSTRAINT uq_gestores_origen UNIQUE (id_origen),
    CONSTRAINT uq_gestores_cedula UNIQUE (cedula)
);

-- Cuentas de coordinación y de apoyo, con su tipo y su territorio.
CREATE TABLE IF NOT EXISTS coordinadores (
    id_coordinador       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen            VARCHAR(100) NOT NULL,

    tipo                 VARCHAR(50)  NOT NULL DEFAULT 'coordinador',
    usuario              VARCHAR(100) NOT NULL,
    clave_hash           VARCHAR(256) NOT NULL,
    nombre               VARCHAR(200) NOT NULL,
    cedula               VARCHAR(20)  NULL,
    correo               VARCHAR(150) NULL,
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion  TIMESTAMPTZ NULL,

    region               VARCHAR(100) NULL,
    departamento         VARCHAR(100) NULL,
    modalidad            VARCHAR(100) NULL,
    nodo                 VARCHAR(100) NULL,
    CONSTRAINT uq_coordinadores_origen  UNIQUE (id_origen),
    CONSTRAINT uq_coordinadores_usuario UNIQUE (usuario),
    CONSTRAINT ck_coordinadores_tipo CHECK
      (tipo IN ('coordinador', 'tecnico_administrativo', 'coordinador_compras', 'coordinador_datos', 'tallerista'))
);

ALTER TABLE coordinadores ADD COLUMN IF NOT EXISTS region       VARCHAR(100) NULL;
