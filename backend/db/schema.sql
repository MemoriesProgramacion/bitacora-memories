ALTER TABLE coordinadores ADD COLUMN IF NOT EXISTS modalidad    VARCHAR(100) NULL;
ALTER TABLE coordinadores ADD COLUMN IF NOT EXISTS nodo         VARCHAR(100) NULL;

-- Representantes de las unidades productivas, identificados por su documento.
CREATE TABLE IF NOT EXISTS representantes (
    id_representante      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento             VARCHAR(20)  NOT NULL,
    documento_inicial     VARCHAR(20)  NULL,
    documentos_rit        VARCHAR(300) NULL,
    documento_expedicion  VARCHAR(100) NULL,
    fecha_nacimiento      DATE NULL,
    nombre1               VARCHAR(60)  NULL,
    nombre2               VARCHAR(60)  NULL,
    apellido1             VARCHAR(60)  NULL,
    apellido2             VARCHAR(60)  NULL,
    sexo                  VARCHAR(20)  NULL,
    telefono1             VARCHAR(30)  NULL,
    telefono2             VARCHAR(30)  NULL,
    correo1               VARCHAR(150) NULL,
    correo2               VARCHAR(150) NULL,
    tiene_correo2         BOOLEAN NULL,
    direccion             VARCHAR(300) NULL,

    nombre_completo       TEXT GENERATED ALWAYS AS (
        btrim(regexp_replace(
            coalesce(nombre1, '') || ' ' || coalesce(nombre2, '') || ' ' ||
            coalesce(apellido1, '') || ' ' || coalesce(apellido2, ''),
            '\s+', ' ', 'g'))
    ) STORED,
    CONSTRAINT uq_representantes_documento UNIQUE (documento)
);

